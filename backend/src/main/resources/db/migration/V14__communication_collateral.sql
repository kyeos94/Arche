-- 문자·팩스·우편 발송, 연락 메모·타임라인(R59), 담보·보증인(R60), 대외 연계 요청 이력 (ADR 0008)

-- integration: 대외 연계 요청 이력 (guide 11.2). 요약은 마스킹된 값만. 추가 전용
CREATE TABLE integration_call_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution  VARCHAR(40)  NOT NULL,
    operation    VARCHAR(40)  NOT NULL,
    summary      VARCHAR(300) NOT NULL,
    elapsed_ms   BIGINT       NOT NULL,
    result_code  VARCHAR(30)  NOT NULL,
    success      BOOLEAN      NOT NULL,
    called_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX integration_call_log_institution_idx ON integration_call_log (institution, id);

-- collection: 팩스·우편 추심 안내도 7일 7회에 1회로 센다 (R59)
ALTER TABLE contact_log DROP CONSTRAINT contact_log_channel_check;
ALTER TABLE contact_log ADD CONSTRAINT contact_log_channel_check
    CHECK (channel IN ('CALL', 'SMS', 'VISIT', 'FAX', 'POST', 'STATUTORY_NOTICE'));

-- communication: 문자·팩스·우편 템플릿. 목적(추심 안내 / 법정·계약상 통지)은 템플릿이 정한다 (R59)
CREATE TABLE message_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)   NOT NULL UNIQUE,
    name        VARCHAR(60)   NOT NULL,
    channel     VARCHAR(10)   NOT NULL CHECK (channel IN ('SMS', 'FAX', 'POST')),
    purpose     VARCHAR(20)   NOT NULL CHECK (purpose IN ('COLLECTION', 'NOTICE')),
    title       VARCHAR(100)  NULL,
    body        VARCHAR(2000) NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL,
    created_by  VARCHAR(30)   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0
);

-- communication: 수동 발송 1건 (문자·팩스·우편). 팩스 번호는 암호문
CREATE TABLE communication_dispatch (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT        NOT NULL,
    customer_id     BIGINT        NOT NULL,
    channel         VARCHAR(10)   NOT NULL CHECK (channel IN ('SMS', 'FAX', 'POST')),
    purpose         VARCHAR(20)   NOT NULL CHECK (purpose IN ('COLLECTION', 'NOTICE')),
    template_id     BIGINT        NULL REFERENCES message_template (id),
    title           VARCHAR(100)  NULL,
    body            VARCHAR(2000) NOT NULL,
    recipient_enc   VARCHAR(512)  NULL,
    status          VARCHAR(20)   NOT NULL CHECK (status IN ('SCHEDULED', 'SENT', 'ACCEPTED', 'IN_TRANSIT',
                                                             'DELIVERED', 'RETURNED', 'FAILED', 'BLOCKED')),
    block_reason    VARCHAR(200)  NULL,
    contact_date    DATE          NOT NULL,
    count_in_window INT           NOT NULL DEFAULT 0,
    contact_log_id  BIGINT        NULL,
    provider_id     VARCHAR(80)   NULL,
    file_ref        VARCHAR(200)  NULL,
    sent_at         TIMESTAMPTZ   NULL,
    delivered_on    DATE          NULL,
    staff_id        BIGINT        NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(30)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX communication_dispatch_account_idx ON communication_dispatch (account_id, id);
CREATE INDEX communication_dispatch_status_idx ON communication_dispatch (status, contact_date);

-- communication: 상담 메모 (연락이 아니라 7일 7회에 세지 않음). 추가 전용
CREATE TABLE contact_memo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT        NOT NULL,
    memo_date   DATE          NOT NULL,
    body        VARCHAR(1000) NOT NULL,
    staff_id    BIGINT        NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    created_by  VARCHAR(30)   NOT NULL
);
CREATE INDEX contact_memo_account_idx ON contact_memo (account_id, id);

-- collateral: 담보 (차량·부동산 공통 필드). 계약은 다른 모듈이라 ID만 저장
CREATE TABLE collateral (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT        NOT NULL,
    type            VARCHAR(20)   NOT NULL CHECK (type IN ('VEHICLE', 'REAL_ESTATE')),
    description     VARCHAR(200)  NOT NULL,
    identifier      VARCHAR(60)   NULL,
    vehicle_class   VARCHAR(20)   NULL,
    model_year      INT           NULL,
    address         VARCHAR(200)  NULL,
    area_m2         NUMERIC(10, 2) NULL,
    senior_claim    BIGINT        NOT NULL DEFAULT 0 CHECK (senior_claim >= 0),
    lien_amount     BIGINT        NOT NULL DEFAULT 0 CHECK (lien_amount >= 0),
    lien_rank       INT           NOT NULL DEFAULT 1 CHECK (lien_rank >= 1),
    status          VARCHAR(20)   NOT NULL CHECK (status IN ('ACTIVE', 'RELEASED')),
    released_on     DATE          NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(30)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    version         BIGINT        NOT NULL DEFAULT 0,
    CHECK (type <> 'VEHICLE' OR (vehicle_class IS NOT NULL AND model_year IS NOT NULL)),
    CHECK (type <> 'REAL_ESTATE' OR (address IS NOT NULL AND area_m2 IS NOT NULL))
);
CREATE INDEX collateral_account_idx ON collateral (account_id);

-- collateral: 시세 조회 이력 (추가 전용). 최근 값으로 LTV를 계산한다 (R60)
CREATE TABLE collateral_valuation (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collateral_id  BIGINT       NOT NULL REFERENCES collateral (id),
    valued_on      DATE         NOT NULL,
    price          BIGINT       NOT NULL CHECK (price >= 0),
    source         VARCHAR(40)  NOT NULL,
    basis          VARCHAR(200) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL
);
CREATE INDEX collateral_valuation_idx ON collateral_valuation (collateral_id, id);

-- collateral: 보증인. 식별번호·연락처는 암호문 + 블라인드 인덱스 (guide 10.2·10.3)
CREATE TABLE guarantor (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        BIGINT       NOT NULL,
    name              VARCHAR(50)  NOT NULL,
    resident_no_enc   VARCHAR(512) NOT NULL,
    resident_no_bidx  CHAR(64)     NOT NULL,
    phone_enc         VARCHAR(512) NULL,
    relation          VARCHAR(30)  NOT NULL,
    guarantee_limit   BIGINT       NOT NULL CHECK (guarantee_limit > 0),
    start_date        DATE         NOT NULL,
    end_date          DATE         NULL,
    status            VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'RELEASED')),
    released_on       DATE         NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    created_by        VARCHAR(30)  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX guarantor_account_idx ON guarantor (account_id);
CREATE UNIQUE INDEX guarantor_active_uq ON guarantor (account_id, resident_no_bidx) WHERE status = 'ACTIVE';

