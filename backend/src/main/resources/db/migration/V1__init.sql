-- 원장은 추가 전용: UPDATE·DELETE 금지 (정정은 REVERSAL 거래)
CREATE FUNCTION forbid_ledger_mutation() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION '원장(%)은 수정·삭제할 수 없습니다. 역분개 거래를 사용하세요', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ledger_entry_append_only BEFORE UPDATE OR DELETE ON ledger_entry
    FOR EACH ROW EXECUTE FUNCTION forbid_ledger_mutation();
CREATE TRIGGER ledger_allocation_append_only BEFORE UPDATE OR DELETE ON ledger_allocation
    FOR EACH ROW EXECUTE FUNCTION forbid_ledger_mutation();

-- superseded는 저장 컬럼이 아니라 REVERSAL이 가리키는 거래라는 파생 상태 (R26)
CREATE VIEW ledger_entry_effective AS
SELECT e.*, EXISTS (SELECT 1 FROM ledger_entry r WHERE r.reversal_of_id = e.id) AS superseded
FROM ledger_entry e;

