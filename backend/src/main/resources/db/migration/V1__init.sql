CREATE TABLE installment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT      NOT NULL REFERENCES loan_account (id),
    schedule_version INT         NOT NULL,
    seq              INT         NOT NULL,
    period_start     DATE        NOT NULL,
    due_date         DATE        NOT NULL,
    grace_end        DATE        NOT NULL,
    principal_due    BIGINT      NOT NULL,
    planned_interest BIGINT      NOT NULL,
    principal_paid   BIGINT      NOT NULL DEFAULT 0,
    status           VARCHAR(30) NOT NULL CHECK (status IN ('PLANNED', 'PAID', 'PARTIALLY_PAID', 'OVERDUE', 'REPLACED')),
    created_at       TIMESTAMPTZ NOT NULL,
