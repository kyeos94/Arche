CREATE TABLE rate_term (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT       NOT NULL REFERENCES loan_account (id),
    contract_rate NUMERIC(5, 2) NOT NULL,
    valid_from    DATE         NOT NULL,
    valid_to      DATE         NULL,
