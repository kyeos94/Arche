-- G13 소멸시효 중단 사유, G14 추심 연락 기록, G19 분할납부 약속, 추심 알림

-- servicing: 소멸시효 중단·10년 연장 사유 (입금은 account_event에서 가져온다)
CREATE TABLE limitation_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT       NOT NULL REFERENCES loan_account (id),
    type        VARCHAR(30)  NOT NULL CHECK (type IN ('PAYMENT_ORDER_FILED', 'SEIZURE', 'JUDGMENT_CONFIRMED')),
    event_date  DATE         NOT NULL,
    memo        VARCHAR(200) NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(30)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX limitation_event_account_idx ON limitation_event (account_id, event_date);

-- collection: 추심 연락 (차단된 시도도 기록하되 한도에는 세지 않는다)
CREATE TABLE contact_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT       NOT NULL,
    contact_date DATE         NOT NULL,
    contacted_at TIMESTAMPTZ  NOT NULL,
    channel      VARCHAR(20)  NOT NULL CHECK (channel IN ('CALL', 'SMS', 'VISIT', 'STATUTORY_NOTICE')),
    result       VARCHAR(20)  NOT NULL CHECK (result IN ('ALLOWED', 'SCHEDULED', 'BLOCKED')),
    count_in_window INT       NOT NULL,
    block_reason VARCHAR(200) NULL,
    memo         VARCHAR(500) NULL,
    staff_id     BIGINT       NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    created_by   VARCHAR(30)  NOT NULL
);
CREATE INDEX contact_log_account_idx ON contact_log (account_id, contact_date);

-- collection: 매입채권 분할납부 약속 (R18). 판정은 입금 내역으로 매번 다시 계산하고, 해제 결과만 저장
CREATE TABLE payment_promise (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT       NOT NULL,
    registered_on      DATE         NOT NULL,
    first_month        DATE         NOT NULL,
    promise_day        INT          NOT NULL CHECK (promise_day BETWEEN 1 AND 31),
    amount             BIGINT       NOT NULL CHECK (amount > 0),
    months             INT          NOT NULL CHECK (months BETWEEN 1 AND 60),
    status             VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'TERMINATED', 'COMPLETED', 'CANCELLED')),
    judged_count       INT          NOT NULL DEFAULT 0,
    terminated_on      DATE         NULL,
    legal_review       BOOLEAN      NOT NULL DEFAULT FALSE,
    memo               VARCHAR(200) NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    created_by         VARCHAR(30)  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL,
    version            BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX payment_promise_account_idx ON payment_promise (account_id);

-- collection: 담당자 알림 (소멸시효 임박·완성, 약속 불이행·해제). 같은 사건은 한 번만
CREATE TABLE collection_alert (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT       NOT NULL,
    staff_id    BIGINT       NULL,
    type        VARCHAR(30)  NOT NULL CHECK (type IN ('LIMITATION_IMMINENT', 'LIMITATION_COMPLETED', 'PROMISE_MISSED',
                                                      'PROMISE_TERMINATED')),
    dedupe_key  VARCHAR(100) NOT NULL UNIQUE,
    message     VARCHAR(300) NOT NULL,
    alert_date  DATE         NOT NULL,
    read_at     TIMESTAMPTZ  NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX collection_alert_staff_idx ON collection_alert (staff_id, read_at);
