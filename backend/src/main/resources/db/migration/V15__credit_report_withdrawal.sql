-- 신용정보 보고(R61), 출금 작성·승인·송금(R62~R64), 과입금 반환 예약 (ADR 0008)

-- creditinfo: 일별 보고 파일. 기준일마다 한 파일
CREATE TABLE credit_report_file (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_date     DATE         NOT NULL UNIQUE,
    file_name     VARCHAR(80)  NOT NULL UNIQUE,
    record_count  INT          NOT NULL,
    byte_length   INT          NOT NULL,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('GENERATED', 'SENT', 'RESULT_RECEIVED')),
    receipt_no    VARCHAR(60)  NULL,
    sent_at       TIMESTAMPTZ  NULL,
    result_at     TIMESTAMPTZ  NULL,
    error_count   INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL,
    created_by    VARCHAR(30)  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE credit_report_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id           BIGINT       NOT NULL REFERENCES credit_report_file (id),
    seq               INT          NOT NULL,
    account_id        BIGINT       NOT NULL,
    record_type       VARCHAR(20)  NOT NULL CHECK (record_type IN ('OPEN', 'DELINQUENCY', 'RELEASE', 'CLOSE')),
    event_date        DATE         NOT NULL,
    balance           BIGINT       NOT NULL,
    delinquency_days  INT          NOT NULL,
    result_code       VARCHAR(10)  NULL,
    result_message    VARCHAR(100) NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    created_by        VARCHAR(30)  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    UNIQUE (file_id, seq)
);
CREATE INDEX credit_report_record_account_idx ON credit_report_record (account_id);

-- creditinfo: 계약별로 기관에 반영된 마지막 상태 (정상 결과를 받은 보고만 반영)
CREATE TABLE credit_report_state (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT       NOT NULL UNIQUE,
    opened         BOOLEAN      NOT NULL DEFAULT FALSE,
    delinquent     BOOLEAN      NOT NULL DEFAULT FALSE,
    closed         BOOLEAN      NOT NULL DEFAULT FALSE,
    last_reported  DATE         NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);

-- treasury: 출금 (guide 6.4). 받는 계좌번호는 암호문, 화면용 마스킹 값을 따로 둔다
CREATE TABLE withdrawal (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    withdrawal_no       VARCHAR(20)  NOT NULL UNIQUE,
    type                VARCHAR(30)  NOT NULL CHECK (type IN ('UNMATCHED_REFUND', 'OVERPAYMENT_REFUND')),
    account_id          BIGINT       NULL,
    unmatched_id        BIGINT       NULL,
    amount              BIGINT       NOT NULL CHECK (amount > 0),
    bank_name           VARCHAR(40)  NOT NULL,
    payee_account_enc   VARCHAR(512) NOT NULL,
    payee_account_masked VARCHAR(40) NOT NULL,
    holder_name         VARCHAR(50)  NOT NULL,
    reason              VARCHAR(200) NOT NULL,
    status              VARCHAR(20)  NOT NULL CHECK (status IN ('REQUESTED', 'FIRST_APPROVED', 'SENDING', 'UNKNOWN',
                                                                'COMPLETED', 'FAILED', 'REJECTED', 'CANCELLED')),
    requested_on        DATE         NOT NULL,
    requested_by        BIGINT       NOT NULL,
    first_approved_by   BIGINT       NULL,
    first_approved_at   TIMESTAMPTZ  NULL,
    final_approved_by   BIGINT       NULL,
    final_approved_at   TIMESTAMPTZ  NULL,
    rejected_by         BIGINT       NULL,
    reject_reason       VARCHAR(200) NULL,
    idempotency_key     VARCHAR(40)  NOT NULL UNIQUE,
    provider_tx_id      VARCHAR(60)  NULL,
    result_code         VARCHAR(30)  NULL,
    result_message      VARCHAR(200) NULL,
    sent_at             TIMESTAMPTZ  NULL,
    completed_at        TIMESTAMPTZ  NULL,
    inquiry_count       INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL,
    created_by          VARCHAR(30)  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    version             BIGINT       NOT NULL DEFAULT 0,
    CHECK ((type = 'UNMATCHED_REFUND' AND unmatched_id IS NOT NULL)
        OR (type = 'OVERPAYMENT_REFUND' AND account_id IS NOT NULL))
);
CREATE INDEX withdrawal_status_idx ON withdrawal (status, id);
-- 미확인 입금 1건에 진행 중인 반환은 하나 (R62)
CREATE UNIQUE INDEX withdrawal_unmatched_active_uq ON withdrawal (unmatched_id)
    WHERE unmatched_id IS NOT NULL AND status NOT IN ('FAILED', 'REJECTED', 'CANCELLED');
CREATE SEQUENCE withdrawal_no_seq START 1001;

-- servicing: 완제 후 과입금 반환 예약(+)·해제(−). 반환 가능액 = 반환 대기액 − 합계 (R62). 추가 전용
CREATE TABLE refund_payout (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT       NOT NULL REFERENCES loan_account (id),
    withdrawal_no  VARCHAR(20)  NOT NULL,
    amount         BIGINT       NOT NULL CHECK (amount <> 0),
    memo           VARCHAR(100) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL
);
CREATE INDEX refund_payout_account_idx ON refund_payout (account_id);
CREATE TRIGGER refund_payout_append_only BEFORE UPDATE OR DELETE ON refund_payout
    FOR EACH ROW EXECUTE FUNCTION forbid_ledger_mutation();
