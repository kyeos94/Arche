-- 채권 생애주기 (정책서 R39~R44, ADR 0005): 상각·매각·환매·매각 후 입금 이전·수기 조정·상계·상태 되돌리기
-- 모두 재생 입력 이벤트(account_event)로 두고, 원장은 엔진 결과와 비교해 역분개 + 새 거래로만 남긴다 (ADR 0002)

ALTER TABLE account_event DROP CONSTRAINT account_event_type_check;
ALTER TABLE account_event ADD CONSTRAINT account_event_type_check
    CHECK (type IN ('PAYMENT', 'PREPAYMENT_REQUEST', 'DUE_DAY_CHANGE', 'COST_CHARGE', 'WORKOUT',
                    'CHARGE_OFF', 'SALE', 'REPURCHASE', 'BUYER_TRANSFER', 'ADJUSTMENT',
                    'SETOFF_OUT', 'SETOFF_IN', 'INTEREST_SUSPENSION'));
-- 수기 조정(R42)은 waive_principal·waive_normal·waive_late를 감액분으로 쓰고, 비용 증감·양수 전 미수이자 감액은 아래 컬럼
ALTER TABLE account_event ADD COLUMN cost_delta BIGINT NULL;
ALTER TABLE account_event ADD COLUMN pre_acq_down BIGINT NULL;
-- 이자 부과 중단(R46) 끝 날짜 (반개구간 [event_date, end_date), null = 계속)
ALTER TABLE account_event ADD COLUMN end_date DATE NULL;
-- 상계(R44) 원천 구분과 짝 이벤트 (원천 SETOFF_OUT ↔ 대상 SETOFF_IN)
ALTER TABLE account_event ADD COLUMN setoff_source VARCHAR(20) NULL CHECK (setoff_source IN ('REFUND', 'SUSPENSE'));
ALTER TABLE account_event ADD COLUMN linked_event_id BIGINT NULL REFERENCES account_event (id);

ALTER TABLE ledger_entry DROP CONSTRAINT ledger_entry_type_check;
ALTER TABLE ledger_entry ADD CONSTRAINT ledger_entry_type_check
    CHECK (type IN ('DISBURSE', 'ACQUIRE', 'REPAYMENT', 'PREPAYMENT', 'PREPAYMENT_FEE', 'COST_CHARGE', 'SUSPENSE_IN',
                    'SUSPENSE_APPLY', 'WAIVER', 'ADJUSTMENT', 'REVERSAL', 'CHARGE_OFF', 'SALE', 'REPURCHASE', 'REFUND',
                    'SALE_TRANSFER', 'SETOFF'));

-- 요약 스냅샷 (ADR 0003과 같은 이유: 목록·상세를 재생 없이 보여주기 위해)
ALTER TABLE loan_account ADD COLUMN charged_off_on DATE NULL;
ALTER TABLE loan_account ADD COLUMN sold_on DATE NULL;
ALTER TABLE loan_account ADD COLUMN transfer_pending BIGINT NOT NULL DEFAULT 0;

-- 매각·환매 기록 (R40·R41). 금액 효과는 account_event(SALE·REPURCHASE)의 재생 결과
CREATE TABLE loan_sale (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT       NOT NULL REFERENCES loan_account (id),
    sale_event_id       BIGINT       NOT NULL REFERENCES account_event (id),
    buyer               VARCHAR(100) NOT NULL,
    sale_price          BIGINT       NOT NULL CHECK (sale_price > 0),
    sold_on             DATE         NOT NULL,
    notice_sent_on      DATE         NOT NULL,
    reason              VARCHAR(200) NULL,
    status              VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'REPURCHASED', 'CANCELLED')),
    repurchase_event_id BIGINT       NULL REFERENCES account_event (id),
    repurchased_on      DATE         NULL,
    repurchase_price    BIGINT       NULL,
    repurchase_reason   VARCHAR(200) NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    created_by          VARCHAR(30)  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    version             BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX loan_sale_account_idx ON loan_sale (account_id);

-- 수기 조정·상계·상태 되돌리기 결재 (R42~R44, 작성자 ≠ 승인자)
CREATE SEQUENCE adjustment_no_seq;
CREATE TABLE adjustment_request (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no        VARCHAR(20)  NOT NULL UNIQUE,
    type              VARCHAR(30)  NOT NULL CHECK (type IN ('ADJUSTMENT', 'SETOFF', 'REVERT_CHARGE_OFF', 'REVERT_SALE',
                                                            'REVERT_SETOFF', 'REVERT_PAYOFF')),
    account_id        BIGINT       NOT NULL REFERENCES loan_account (id),
    source_account_id BIGINT       NULL REFERENCES loan_account (id),
    setoff_source     VARCHAR(20)  NULL CHECK (setoff_source IN ('REFUND', 'SUSPENSE')),
    principal_down    BIGINT       NOT NULL DEFAULT 0,
    normal_down       BIGINT       NOT NULL DEFAULT 0,
    late_down         BIGINT       NOT NULL DEFAULT 0,
    cost_delta        BIGINT       NOT NULL DEFAULT 0,
    pre_acq_down      BIGINT       NOT NULL DEFAULT 0,
    amount            BIGINT       NOT NULL DEFAULT 0,
    target_event_id   BIGINT       NULL REFERENCES account_event (id),
    reason            VARCHAR(200) NOT NULL,
    status            VARCHAR(20)  NOT NULL CHECK (status IN ('REQUESTED', 'APPLIED', 'REJECTED', 'CONSUMED')),
    requested_by      BIGINT       NOT NULL,
    requested_on      DATE         NOT NULL,
    decided_by        BIGINT       NULL,
    decided_on        DATE         NULL,
    applied_event_id  BIGINT       NULL REFERENCES account_event (id),
    consumed_on       DATE         NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    created_by        VARCHAR(30)  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX adjustment_request_status_idx ON adjustment_request (status, id);
CREATE INDEX adjustment_request_account_idx ON adjustment_request (account_id);
