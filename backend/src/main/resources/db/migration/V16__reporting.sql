-- reporting 모듈 (ADR 0009, 정책서 R65~R68)

-- ===================================================================== 일보 스냅샷 (R65)
CREATE TABLE report_daily (
    business_date  DATE        NOT NULL PRIMARY KEY,
    created_at     TIMESTAMPTZ NOT NULL,
    created_by     VARCHAR(30) NOT NULL,
    journal_debit  BIGINT      NOT NULL,
    journal_credit BIGINT      NOT NULL,
    unmapped_count INT         NOT NULL
);

-- (구역, 항목)을 행으로 두어 새 거래유형·상태가 생겨도 스키마를 바꾸지 않는다
CREATE TABLE report_daily_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE        NOT NULL REFERENCES report_daily (business_date),
    section       VARCHAR(30) NOT NULL,
    item          VARCHAR(60) NOT NULL,
    item_count    BIGINT      NOT NULL,
    amount        BIGINT      NOT NULL,
    UNIQUE (business_date, section, item)
);

-- 마감일의 계정별 일계. 매핑을 나중에 바꿔도 과거 일계는 바뀌지 않는다 (R68)
CREATE TABLE report_journal_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE        NOT NULL REFERENCES report_daily (business_date),
    account_code  VARCHAR(30) NOT NULL,
    debit         BIGINT      NOT NULL,
    credit        BIGINT      NOT NULL,
    UNIQUE (business_date, account_code)
);

-- ===================================================================== 월마감 (R66)
CREATE TABLE report_month_end (
    month      DATE        NOT NULL PRIMARY KEY CHECK (EXTRACT(DAY FROM month) = 1),
    as_of      DATE        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    created_by VARCHAR(30) NOT NULL
);

CREATE TABLE report_month_end_account (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month             DATE        NOT NULL REFERENCES report_month_end (month),
    account_id        BIGINT      NOT NULL,
    account_no        VARCHAR(20) NOT NULL,
    product_code      VARCHAR(10) NOT NULL,
    status            VARCHAR(30) NOT NULL,
    bucket            VARCHAR(20) NOT NULL,
    delinquency_days  INT         NOT NULL,
    principal_balance BIGINT      NOT NULL,
    claim_balance     BIGINT      NOT NULL,
    UNIQUE (month, account_id)
);

-- ===================================================================== 대손충당금 적립률 (R67, 가상 값)
CREATE TABLE provision_rate (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket     VARCHAR(20)   NOT NULL CHECK (bucket IN ('CURRENT', 'D1_30', 'D31_60', 'D61_90', 'D91_PLUS',
                                                        'ACCELERATED')),
    rate       NUMERIC(5, 2) NOT NULL CHECK (rate >= 0 AND rate <= 100),
    valid_from DATE          NOT NULL,
    UNIQUE (bucket, valid_from)
);

