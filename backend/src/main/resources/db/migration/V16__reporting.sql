CREATE TABLE journal_rule (
    posting_type    VARCHAR(30)  NOT NULL PRIMARY KEY,
    mode            VARCHAR(10)  NOT NULL CHECK (mode IN ('BOOK', 'SETTLE')),
    counter_account VARCHAR(30)  NOT NULL REFERENCES journal_account (code),
    book_account    VARCHAR(30)  NULL REFERENCES journal_account (code),
    description     VARCHAR(100) NOT NULL,
    CHECK (mode = 'SETTLE' OR book_account IS NOT NULL)
);

