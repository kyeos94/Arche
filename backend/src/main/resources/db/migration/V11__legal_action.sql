-- 범위 밖 기능 B: 법조치 상세 — 지급명령·압류·경매 (R51), 법조치 비용 (R52)
-- 법원명·사건번호는 자유 입력이며 형식을 검사하지 않는다 (실제 기관 코드 체계를 넣지 않음)

CREATE SEQUENCE legal_action_no_seq START 1001;

CREATE TABLE legal_action (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_no    VARCHAR(20)  NOT NULL UNIQUE,
    account_id   BIGINT       NOT NULL,
    type         VARCHAR(20)  NOT NULL CHECK (type IN ('PAYMENT_ORDER', 'SEIZURE', 'AUCTION')),
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('FILED', 'ISSUED', 'SERVED', 'OBJECTED', 'CONFIRMED',
                                                         'ORDERED', 'COLLECTED', 'COMMENCED', 'SALE_SCHEDULED',
                                                         'SOLD', 'DISTRIBUTED', 'CLOSED', 'WITHDRAWN', 'DISMISSED',
                                                         'RELEASED')),
    court_name   VARCHAR(100) NULL,
    case_ref     VARCHAR(50)  NULL,
    target_desc  VARCHAR(200) NULL,
    claim_amount BIGINT       NULL CHECK (claim_amount >= 0),
    filed_on     DATE         NOT NULL,
    closed_on    DATE         NULL,
    memo         VARCHAR(500) NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    created_by   VARCHAR(30)  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    version      BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX legal_action_account_idx ON legal_action (account_id);

-- 단계 이력 (추가 전용). 소멸시효 사유를 남긴 단계는 limitation_event.id를 가리킨다
CREATE TABLE legal_action_stage (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_action_id     BIGINT       NOT NULL REFERENCES legal_action (id),
    stage               VARCHAR(20)  NOT NULL,
    stage_date          DATE         NOT NULL,
    memo                VARCHAR(200) NULL,
    limitation_event_id BIGINT       NULL,
    staff_id            BIGINT       NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    created_by          VARCHAR(30)  NOT NULL
);
CREATE INDEX legal_action_stage_action_idx ON legal_action_stage (legal_action_id, id);

-- 비용 (추가 전용). 등록 업무일자에 계약 비용(COST)으로 적재한다 (R52)
CREATE TABLE legal_action_cost (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_action_id BIGINT       NOT NULL REFERENCES legal_action (id),
    cost_type       VARCHAR(20)  NOT NULL CHECK (cost_type IN ('COURT_FEE', 'SERVICE_FEE', 'EXECUTION_FEE',
                                                                'AGENT_FEE', 'OTHER')),
    amount          BIGINT       NOT NULL CHECK (amount > 0),
    incurred_on     DATE         NOT NULL,
    charged_on      DATE         NOT NULL,
    memo            VARCHAR(200) NULL,
    staff_id        BIGINT       NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(30)  NOT NULL
);
CREATE INDEX legal_action_cost_action_idx ON legal_action_cost (legal_action_id);
