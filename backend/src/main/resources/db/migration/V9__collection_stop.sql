-- 추심 중지 (정책서 R45·R46, ADR 0005): 사망(상속)·개인회생·파산·공적 채무조정(가상)
-- 사유는 채무자 단위라 등록 시 그 고객의 열린 계약마다 한 행씩, 같은 group_no로 묶는다 (해제도 묶음 단위)
CREATE SEQUENCE collection_stop_group_seq;
CREATE TABLE collection_stop (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_no            VARCHAR(20)   NOT NULL,
    account_id          BIGINT        NOT NULL,
    customer_id         BIGINT        NOT NULL,
    reason              VARCHAR(30)   NOT NULL CHECK (reason IN ('DECEASED', 'REHABILITATION', 'BANKRUPTCY',
                                                                 'PUBLIC_WORKOUT')),
    effective_date      DATE          NOT NULL,
    memo                VARCHAR(200)  NOT NULL,
    status              VARCHAR(20)   NOT NULL CHECK (status IN ('ACTIVE', 'RELEASED')),
    released_on         DATE          NULL,
    release_reason      VARCHAR(200)  NULL,
    -- servicing 이자 부과 중단 재생 이벤트 (개인회생·파산, R46). 모듈이 달라 FK 없이 id만
    interest_event_id   BIGINT        NULL,
    -- 공적 채무조정(가상) 확정 시 조정 금리와 적용일 (R46)
    relief_rate         NUMERIC(5, 2) NULL,
    relief_from         DATE          NULL,
    created_at          TIMESTAMPTZ   NOT NULL,
    created_by          VARCHAR(30)   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    version             BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX collection_stop_account_idx ON collection_stop (account_id, status);
CREATE INDEX collection_stop_group_idx ON collection_stop (group_no);
