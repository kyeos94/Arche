-- 연락 유예 (정책서 6장: 최대 3개월, 1회 연장)와 자동 문자 (약정일 3일 전 납입 안내, 연체 1·7·30일째, 완제 안내)

CREATE TABLE contact_deferral (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT       NOT NULL,
    start_date   DATE         NOT NULL,
    end_date     DATE         NOT NULL,
    original_end DATE         NOT NULL,
    extended     BOOLEAN      NOT NULL DEFAULT FALSE,
    reason       VARCHAR(200) NOT NULL,
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'ENDED')),
    ended_on     DATE         NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    created_by   VARCHAR(30)  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    version      BIGINT       NOT NULL DEFAULT 0,
    CHECK (end_date >= start_date)
);
CREATE INDEX contact_deferral_account_idx ON contact_deferral (account_id, start_date);

CREATE TABLE outbound_message (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT       NOT NULL,
    customer_id    BIGINT       NOT NULL,
    type           VARCHAR(30)  NOT NULL CHECK (type IN ('PAYMENT_REMINDER', 'DELINQUENCY_1', 'DELINQUENCY_7',
                                                         'DELINQUENCY_30', 'PAYOFF', 'PROMISE_REMINDER')),
    dedupe_key     VARCHAR(100) NOT NULL UNIQUE,
    body           VARCHAR(500) NOT NULL,
    scheduled_date DATE         NOT NULL,
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('SCHEDULED', 'SENT', 'SKIPPED')),
    skip_reason    VARCHAR(200) NULL,
    sent_at        TIMESTAMPTZ  NULL,
    provider_id    VARCHAR(60)  NULL,
    contact_log_id BIGINT       NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX outbound_message_due_idx ON outbound_message (status, scheduled_date);
CREATE INDEX outbound_message_account_idx ON outbound_message (account_id);
