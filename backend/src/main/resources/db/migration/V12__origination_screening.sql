-- 심사 상세 1: 접수 채널 정규화, 자동 거절(R53), 서류 징구(R54), 심사자 배정(R55), 동의·신용조회, 본인인증 랜딩(R58)

-- ===================================================================== 신청 확장
ALTER TABLE loan_application
    ADD COLUMN channel            VARCHAR(20)  NOT NULL DEFAULT 'STAFF'
        CHECK (channel IN ('STAFF', 'BROKER', 'PLATFORM')),
    ADD COLUMN intake_source      VARCHAR(30)  NULL,      -- 플랫폼 코드 또는 중개업자 번호
    ADD COLUMN external_ref       VARCHAR(60)  NULL,      -- 플랫폼·중개업자 쪽 신청 번호 (중복 접수 방지)
    ADD COLUMN assigned_at        TIMESTAMPTZ  NULL,      -- 마지막 배정 시각 (배정 동률 판정, R55)
    ADD COLUMN decided_on         DATE         NULL,      -- 승인·거절 업무일자 (30일 거절 이력, R53)
    ADD COLUMN reject_reason_code VARCHAR(30)  NULL;

CREATE UNIQUE INDEX loan_application_external_uk ON loan_application (intake_source, external_ref)
    WHERE external_ref IS NOT NULL;
CREATE INDEX loan_application_customer_idx ON loan_application (customer_id, status);
CREATE INDEX loan_application_underwriter_idx ON loan_application (underwriter_id, status);

-- 기존 거절 건의 거절일을 상태 이력에서 채운다
UPDATE loan_application a
SET decided_on = (SELECT max((h.changed_at AT TIME ZONE 'Asia/Seoul')::date)
                  FROM application_status_history h
                  WHERE h.application_id = a.id AND h.to_status IN ('APPROVED', 'REJECTED'))
WHERE a.status IN ('APPROVED', 'REJECTED', 'CONTRACTED', 'DISBURSED');

-- ===================================================================== 동의 (guide 11.2)
CREATE TABLE application_consent (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES loan_application (id),
    consent_type   VARCHAR(30)  NOT NULL CHECK (consent_type IN ('CREDIT_INQUIRY')),
    channel        VARCHAR(20)  NOT NULL CHECK (channel IN ('STAFF', 'BROKER', 'PLATFORM', 'LANDING')),
    agreed_on      DATE         NOT NULL,
    valid_until    DATE         NOT NULL,
    evidence       VARCHAR(100) NULL,         -- 서면 동의서 번호, 플랫폼 동의 참조 등
    withdrawn_at   TIMESTAMPTZ  NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX application_consent_app_idx ON application_consent (application_id, consent_type);

-- ===================================================================== 신용조회 결과
CREATE TABLE credit_inquiry (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id       BIGINT      NULL REFERENCES loan_application (id),
    customer_id          BIGINT      NOT NULL,
    consent_ref          VARCHAR(40) NOT NULL,   -- 'CONSENT-{id}' 또는 'PLATFORM-{한도조회 번호}'
    inquiry_ref          VARCHAR(60) NOT NULL,
    grade                INT         NOT NULL CHECK (grade BETWEEN 1 AND 10),
    currently_delinquent BOOLEAN     NOT NULL,
    open_loan_count      INT         NOT NULL,
    total_debt           BIGINT      NOT NULL,
    inquired_on          DATE        NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL,
    created_by           VARCHAR(30) NOT NULL
);
CREATE INDEX credit_inquiry_app_idx ON credit_inquiry (application_id);

-- ===================================================================== 자동 거절 규칙 결과 (R53)
CREATE TABLE screening_result (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES loan_application (id),
    rule_code      VARCHAR(30)  NOT NULL CHECK (rule_code IN ('MIN_AGE', 'DUPLICATE_APPLICATION', 'RECENT_REJECTION',
                                     'INTERNAL_HISTORY', 'CREDIT_BUREAU')),
    outcome        VARCHAR(10)  NOT NULL CHECK (outcome IN ('PASS', 'REJECT', 'SKIPPED')),
    detail         VARCHAR(200) NOT NULL,
    screened_on    DATE         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    UNIQUE (application_id, rule_code)
);

-- ===================================================================== 서류 징구 (R54)
CREATE TABLE document_requirement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(10) NOT NULL,
    doc_type     VARCHAR(30) NOT NULL CHECK (doc_type IN ('ID_CARD', 'INCOME_PROOF', 'EMPLOYMENT_PROOF',
                                  'VEHICLE_REGISTRATION', 'PROPERTY_REGISTRY')),
    required     BOOLEAN     NOT NULL,
    sort_order   INT         NOT NULL,
    UNIQUE (product_code, doc_type)
);

