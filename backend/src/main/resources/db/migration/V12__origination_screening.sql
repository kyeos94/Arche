CREATE TABLE application_document (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES loan_application (id),
    doc_type       VARCHAR(30)  NOT NULL CHECK (doc_type IN ('ID_CARD', 'INCOME_PROOF', 'EMPLOYMENT_PROOF',
                                    'VEHICLE_REGISTRATION', 'PROPERTY_REGISTRY')),
    required       BOOLEAN      NOT NULL,
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('REQUESTED', 'RECEIVED', 'VERIFIED', 'REJECTED')),
    received_via   VARCHAR(20)  NULL CHECK (received_via IN ('UPLOAD', 'PAPER', 'LANDING', 'BROKER')),
    storage_key    VARCHAR(100) NULL,
    file_name      VARCHAR(200) NULL,
    content_type   VARCHAR(100) NULL,
    size_bytes     BIGINT       NULL,
    sha256         VARCHAR(64)     NULL,
    received_at    TIMESTAMPTZ  NULL,
    reviewed_by    VARCHAR(30)  NULL,
    reviewed_at    TIMESTAMPTZ  NULL,
    note           VARCHAR(200) NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    UNIQUE (application_id, doc_type)
);

-- ===================================================================== 심사자 프로필 (R55)
-- staff_id는 staff 모듈의 ID (모듈이 달라 FK 없음, guide 16.4)
CREATE TABLE underwriter_profile (
    staff_id      BIGINT      PRIMARY KEY,
    product_codes VARCHAR(60) NOT NULL,   -- 쉼표 구분 (예: 'P1,P2,P5')
    available     BOOLEAN     NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by    VARCHAR(30) NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0
);

-- ===================================================================== 본인인증 랜딩 (guide 11.3, R58)
CREATE TABLE identity_verification (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id       BIGINT      NOT NULL REFERENCES loan_application (id),
    customer_id          BIGINT      NOT NULL,
    token_hash           VARCHAR(64)    NOT NULL UNIQUE,   -- 일회용 토큰의 SHA-256 (원문은 저장하지 않음)
    status               VARCHAR(20) NOT NULL CHECK (status IN ('ISSUED', 'VERIFIED', 'COMPLETED', 'FAILED')),
    expires_at           TIMESTAMPTZ NOT NULL,
    failed_attempts      INT         NOT NULL DEFAULT 0,
    connecting_info_hash VARCHAR(64)    NULL,
    verified_at          TIMESTAMPTZ NULL,
    completed_at         TIMESTAMPTZ NULL,
    created_at           TIMESTAMPTZ NOT NULL,
    created_by           VARCHAR(30) NOT NULL,
    updated_at           TIMESTAMPTZ NOT NULL,
    version              BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX identity_verification_app_idx ON identity_verification (application_id);
