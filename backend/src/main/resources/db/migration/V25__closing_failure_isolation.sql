-- 일마감 계약 단위 실패 격리 (R76, ADR 0012)

-- 판정에 실패한 계약 수 (그 계약만 롤백되고 마감은 진행)
ALTER TABLE daily_closing ADD COLUMN judge_failures INT NOT NULL DEFAULT 0;

-- 일보 스냅샷의 "미판정 계약 N건"
ALTER TABLE report_daily ADD COLUMN unjudged_count INT NOT NULL DEFAULT 0;

-- 일마감 판정 실패 기록. 추가만 하고, 수정은 해결 표시(resolved_at·resolved_by를 한 번 채우기)만 허용한다
CREATE TABLE daily_closing_failure (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE         NOT NULL,
    account_id    BIGINT       NOT NULL,
    error_kind    VARCHAR(10)  NOT NULL CHECK (error_kind IN ('BUSINESS', 'SYSTEM')),
    error_code    VARCHAR(60)  NOT NULL,
    message       VARCHAR(200) NOT NULL,
    recorded_at   TIMESTAMPTZ  NOT NULL,
    resolved_at   TIMESTAMPTZ  NULL,
    resolved_by   VARCHAR(30)  NULL,
    CHECK ((resolved_at IS NULL) = (resolved_by IS NULL))
);
CREATE INDEX daily_closing_failure_date_idx ON daily_closing_failure (business_date);
CREATE INDEX daily_closing_failure_open_idx ON daily_closing_failure (account_id) WHERE resolved_at IS NULL;

CREATE FUNCTION daily_closing_failure_guard() RETURNS trigger AS
$$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION '일마감 실패 기록은 삭제할 수 없습니다';
    END IF;
    IF OLD.resolved_at IS NOT NULL OR NEW.resolved_at IS NULL
        OR (NEW.id, NEW.business_date, NEW.account_id, NEW.error_kind, NEW.error_code, NEW.message, NEW.recorded_at)
            IS DISTINCT FROM
           (OLD.id, OLD.business_date, OLD.account_id, OLD.error_kind, OLD.error_code, OLD.message, OLD.recorded_at)
    THEN
        RAISE EXCEPTION '일마감 실패 기록은 해결 표시만 할 수 있습니다';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER daily_closing_failure_append_only BEFORE UPDATE OR DELETE ON daily_closing_failure
    FOR EACH ROW EXECUTE FUNCTION daily_closing_failure_guard();
