-- 심사 상세 2: 중개업자·중개수수료 정산·환수(R56), 대출 비교 플랫폼 3단계 접수(R57), 랜딩 링크 무효화(R58)

-- ===================================================================== 중개업자 (guide 2.1, 2.3)
CREATE SEQUENCE broker_no_seq START 1001;

CREATE TABLE broker (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broker_no       VARCHAR(20)  NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    registration_no VARCHAR(30)  NOT NULL UNIQUE,   -- 가상 등록 번호 (실제 등록 체계와 무관)
    api_key_hash    VARCHAR(64)  NOT NULL UNIQUE,   -- API 키의 SHA-256 (원문은 발급 때 한 번만 보여줌)
    allowed_ips     VARCHAR(200) NULL,              -- 쉼표 구분. 비어 있으면 IP 제한 없음
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    created_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(30)  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0
);

-- 수수료율 이력 [valid_from, valid_to). 겹침 금지 (guide 16.4)
CREATE TABLE broker_commission_rate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broker_id   BIGINT        NOT NULL REFERENCES broker (id),
    rate        NUMERIC(5, 2) NOT NULL CHECK (rate >= 0 AND rate <= 4.00),
    valid_from  DATE          NOT NULL,
    valid_to    DATE          NULL,
    reason      VARCHAR(200)  NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    created_by  VARCHAR(30)   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT broker_rate_no_overlap EXCLUDE USING gist (broker_id WITH =, daterange(valid_from, valid_to) WITH &&)
);

ALTER TABLE loan_application ADD COLUMN broker_id BIGINT NULL REFERENCES broker (id);

-- 정산·환수 (추가 전용: 환수는 음수 금액의 새 행, 정산 행은 고치지 않는다)
CREATE TABLE broker_commission (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broker_id      BIGINT        NOT NULL REFERENCES broker (id),
    application_id BIGINT        NOT NULL REFERENCES loan_application (id),
    entry_type     VARCHAR(20)   NOT NULL CHECK (entry_type IN ('SETTLEMENT', 'CLAWBACK')),
    base_amount    BIGINT        NOT NULL,
    rate           NUMERIC(5, 2) NOT NULL,
    amount         BIGINT        NOT NULL,
    occurred_on    DATE          NOT NULL,
    reason_code    VARCHAR(30)   NULL CHECK (reason_code IN ('EARLY_PAYOFF', 'MIS_SELLING')),
    reason         VARCHAR(200)  NULL,
    created_at     TIMESTAMPTZ   NOT NULL,
    created_by     VARCHAR(30)   NOT NULL,
    UNIQUE (application_id, entry_type)
);
CREATE INDEX broker_commission_broker_idx ON broker_commission (broker_id, occurred_on);

-- ===================================================================== 대출 비교 플랫폼 (guide 2.1, R57)
CREATE SEQUENCE platform_inquiry_no_seq START 1001;

-- 1단계 한도조회. 식별번호 평문은 저장하지 않고 블라인드 인덱스만 둔다 (2단계 신청에서 동일인 확인)
CREATE TABLE platform_inquiry (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_no           VARCHAR(20)   NOT NULL UNIQUE,
    platform_code        VARCHAR(20)   NOT NULL,
    platform_ref         VARCHAR(60)   NOT NULL,
    resident_no_bidx     VARCHAR(64)   NOT NULL,
    product_code         VARCHAR(10)   NOT NULL,
    requested_amount     BIGINT        NOT NULL,
    term_months          INT           NOT NULL,
    consent_ref          VARCHAR(60)   NOT NULL,
    credit_inquiry_ref   VARCHAR(60)   NULL,
    credit_grade         INT           NULL,
    offered              BOOLEAN       NOT NULL,
    offered_limit        BIGINT        NULL,
    offered_rate         NUMERIC(5, 2) NULL,
    decline_reason       VARCHAR(100)  NULL,
    inquired_on          DATE          NOT NULL,
    valid_until          DATE          NOT NULL,
    application_id       BIGINT        NULL UNIQUE REFERENCES loan_application (id),
    created_at           TIMESTAMPTZ   NOT NULL,
    created_by           VARCHAR(30)   NOT NULL,
    updated_at           TIMESTAMPTZ   NOT NULL,
    version              BIGINT        NOT NULL DEFAULT 0,
    UNIQUE (platform_code, platform_ref)
);

-- 3단계 결과 통보 (결과별 1행, 실패하면 재통보로 attempts 증가)
CREATE TABLE platform_result_notice (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES loan_application (id),
    platform_code  VARCHAR(20)  NOT NULL,
    result         VARCHAR(20)  NOT NULL CHECK (result IN ('APPROVED', 'REJECTED', 'WITHDRAWN')),
    delivered      BOOLEAN      NOT NULL,
    receipt_id     VARCHAR(60)  NULL,
    attempts       INT          NOT NULL,
    last_sent_at   TIMESTAMPTZ  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    UNIQUE (application_id, result)
);

