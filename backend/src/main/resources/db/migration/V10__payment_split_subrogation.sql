-- 범위 밖 기능 B: 일괄 입금 배분(R47·R48), 입금자 구분·대위변제(R49), 소멸시효 미반영(R50), 배당금·공탁금 채널(R52)

-- payment: 법원 배당금·공탁금 출급 채널 (R52)
ALTER TABLE payment DROP CONSTRAINT IF EXISTS payment_channel_check;
ALTER TABLE payment ADD CONSTRAINT payment_channel_check
    CHECK (channel IN ('VIRTUAL_ACCOUNT', 'BANK_TRANSFER', 'AUTO_DEBIT', 'CASH', 'AUCTION_DISTRIBUTION', 'COURT_DEPOSIT'));

-- payment: 일괄 배분 원 입금 (R48)
ALTER TABLE payment DROP CONSTRAINT IF EXISTS payment_status_check;
ALTER TABLE payment ADD CONSTRAINT payment_status_check
    CHECK (status IN ('RECEIVED', 'ALLOCATED', 'UNMATCHED', 'REVERSED', 'CANCELLED', 'SPLIT'));

-- 하위 입금 거래고유번호 = 원 번호 + "-S{n}"
ALTER TABLE payment ALTER COLUMN bank_tx_id TYPE VARCHAR(60);

ALTER TABLE payment
    ADD COLUMN parent_payment_id BIGINT       NULL REFERENCES payment (id),
    ADD COLUMN split_method      VARCHAR(30)  NULL
        CHECK (split_method IN ('OLDEST_DELINQUENCY_FIRST', 'PROPORTIONAL', 'MANUAL')),
    ADD COLUMN payer_type        VARCHAR(20)  NOT NULL DEFAULT 'CUSTOMER'
        CHECK (payer_type IN ('CUSTOMER', 'GUARANTOR', 'THIRD_PARTY')),
    -- 보증인·제3자 이름은 개인정보: EncryptedStringConverter (R49)
    ADD COLUMN payer_name_enc    VARCHAR(512) NULL,
    ADD COLUMN payer_ref         VARCHAR(100) NULL,
    -- collection 모듈 legal_action.id (모듈 간 FK는 두지 않음)
    ADD COLUMN legal_action_id   BIGINT       NULL;
CREATE INDEX payment_parent_idx ON payment (parent_payment_id) WHERE parent_payment_id IS NOT NULL;
CREATE INDEX payment_legal_action_idx ON payment (legal_action_id) WHERE legal_action_id IS NOT NULL;

-- servicing: 채무자 승인이 아닌 입금은 소멸시효 중단으로 세지 않음 (R50). 재생 입력에는 영향 없음
ALTER TABLE account_event ADD COLUMN limitation_excluded BOOLEAN NOT NULL DEFAULT FALSE;

-- payment: 대위변제 기록 (R49). 회사는 기록만 하고 구상권 금액을 지급·보증하지 않는다
CREATE TABLE subrogation_claim (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     BIGINT       NOT NULL REFERENCES payment (id),
    account_id     BIGINT       NOT NULL,
    payer_type     VARCHAR(20)  NOT NULL CHECK (payer_type IN ('GUARANTOR', 'THIRD_PARTY')),
    payer_name_enc VARCHAR(512) NOT NULL,
    payer_ref      VARCHAR(100) NULL,
    value_date     DATE         NOT NULL,
    amount         BIGINT       NOT NULL CHECK (amount > 0),
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'CANCELLED')),
    recorded_on    DATE         NOT NULL,
    cancelled_on   DATE         NULL,
    cancel_reason  VARCHAR(200) NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(30)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX subrogation_claim_account_idx ON subrogation_claim (account_id);
CREATE UNIQUE INDEX subrogation_claim_active_uk ON subrogation_claim (payment_id) WHERE status = 'ACTIVE';

-- servicing: 법조치 취하·각하로 중단 효력이 없어진 사유 (R51). 행은 지우지 않고 무효 표시
ALTER TABLE limitation_event
    ADD COLUMN voided_on   DATE         NULL,
    ADD COLUMN void_reason VARCHAR(200) NULL;
